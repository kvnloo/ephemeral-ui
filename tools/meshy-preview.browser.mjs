// Serve src/ with python3 -m http.server --directory src.
// Run: node tools/meshy-preview.browser.mjs <site-url>
// Optional: PLAYWRIGHT_FROM points to a package.json beside an external Playwright install;
// CHROMIUM_PATH sets a system Chromium executable instead of Playwright's bundled browser.
import assert from "node:assert/strict";
import { createRequire } from "node:module";
import { readFileSync } from "node:fs";

const { chromium } = createRequire(process.env.PLAYWRIGHT_FROM ?? import.meta.url)("playwright");
const catalog = JSON.parse(readFileSync(new URL("../catalog/catalog.json", import.meta.url)));
const plugins = catalog.kinds.find(({ kind }) => kind === "plugin").fixtures;
const fixture = plugins.find(({ card }) => card.app === "meshy");
const other = plugins.find(({ card }) => card.app === "google-meet");
assert.equal(fixture.props.simulated, true);
assert.equal(fixture.props.previewAsset.source, "Blender");
assert.equal(fixture.props.previewAsset.status, "placeholder");

const browser = await chromium.launch({
  executablePath: process.env.CHROMIUM_PATH,
  args: ["--enable-unsafe-swiftshader", "--use-angle=swiftshader"],
});
try {
  const page = await browser.newPage({ viewport: { width: 1120, height: 900 } });
  page.setDefaultTimeout(20000);
  const url = process.argv[2];
  const asset = page.waitForResponse(new URL(fixture.props.previewAsset.path, url).href);
  await page.goto(url);
  const plugin = page.locator('#kindgrid [data-kind="plugin"][data-app="meshy"]');
  await plugin.getByText("Blender placeholder · not generated by Meshy", { exact: true }).waitFor();
  await plugin.getByRole("button", { name: "Hold to simulate run" }).waitFor();
  assert.equal((await asset).ok(), true);
  const canvas = plugin.locator("canvas.v3-cv");
  await canvas.scrollIntoViewIfNeeded();
  await plugin.getByText(/heron\.glb · .* verts · Blender sample/).waitFor();
  await plugin.locator(".g3-st li.done").nth(4).waitFor({ timeout: 45000 });

  // Hold the pointer still over the viewport to disable auto-orbit. Pixel changes
  // after the model fade-in then reflect the embedded animation, not camera movement.
  const bounds = await canvas.boundingBox();
  await page.mouse.move(bounds.x + bounds.width / 2, bounds.y + bounds.height / 2);
  await page.mouse.down();
  const frame = await canvas.evaluate(el => el.toDataURL());
  await page.waitForFunction(frame => {
    const canvas = document.querySelector('#kindgrid [data-kind="plugin"][data-app="meshy"] canvas');
    return canvas.toDataURL() !== frame;
  }, frame);
  await page.mouse.up();
  console.log("PASS Meshy fixture labels the Blender placeholder; GLB loaded and animated with camera fixed");

  const otherPage = await browser.newPage();
  await otherPage.goto(new URL("#app=" + other.card.app, url).href);
  const otherCard = otherPage.locator(`#drawer [data-kind="plugin"][data-app="${other.card.app}"]`);
  await otherCard.getByText(other.props.tools[0].tool, { exact: true }).waitFor();
  assert.equal(await otherCard.locator(".pl-view").count(), 0);
  console.log("PASS Google Meet Hermes plugin fixture renders without a Meshy preview");
} finally {
  await browser.close();
}
